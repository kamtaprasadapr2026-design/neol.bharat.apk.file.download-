package com.example.util

import android.content.Context
import android.graphics.Color
import android.graphics.Paint
import android.graphics.pdf.PdfDocument
import com.example.model.Receipt
import java.io.File
import java.io.FileOutputStream
import java.text.SimpleDateFormat
import java.util.Locale

object ReceiptPdfGenerator {

    fun generateA4ReceiptPdf(context: Context, receipt: Receipt): File? {
        val pdfDocument = PdfDocument()
        // A4 Dimensions at 72 DPI: 595 x 842 points
        val pageInfo = PdfDocument.PageInfo.Builder(595, 842, 1).create()
        val page = pdfDocument.startPage(pageInfo)
        val canvas = page.canvas

        val paint = Paint()
        val titlePaint = Paint().apply {
            color = Color.rgb(30, 41, 59) // Dark navy
            textSize = 24f
            isFakeBoldText = true
        }
        val headerPaint = Paint().apply {
            color = Color.rgb(2, 132, 199) // Sky blue accent
            textSize = 14f
            isFakeBoldText = true
        }
        val regularPaint = Paint().apply {
            color = Color.rgb(51, 65, 85)
            textSize = 12f
        }
        val boldPaint = Paint().apply {
            color = Color.rgb(15, 23, 42)
            textSize = 12f
            isFakeBoldText = true
        }

        // Header Background Banner
        val bannerPaint = Paint().apply {
            color = Color.rgb(241, 245, 249)
        }
        canvas.drawRect(0f, 0f, 595f, 110f, bannerPaint)

        // Title and Subtitle
        canvas.drawText("NEOL BHARAT", 40f, 50f, titlePaint)
        canvas.drawText("Official Payment Receipt / भुगतान रसीद", 40f, 75f, headerPaint)
        canvas.drawText("Verified & Digitally Generated", 40f, 95f, regularPaint)

        // Receipt Meta info box
        var y = 140f
        canvas.drawText("Receipt No: ${receipt.receiptNumber}", 40f, y, boldPaint)
        val sdf = SimpleDateFormat("dd MMM yyyy, hh:mm a", Locale.getDefault())
        val dateStr = receipt.paymentDate?.toDate()?.let { sdf.format(it) } ?: "Verified"
        canvas.drawText("Date: $dateStr", 380f, y, regularPaint)

        y += 25f
        canvas.drawLine(40f, y, 555f, y, paint.apply { color = Color.LTGRAY; strokeWidth = 1f })

        // Student & Payer Info
        y += 30f
        canvas.drawText("STUDENT DETAILS", 40f, y, headerPaint)
        y += 20f
        canvas.drawText("Student Name:", 40f, y, boldPaint)
        canvas.drawText(receipt.studentName, 160f, y, regularPaint)
        y += 20f
        canvas.drawText("Student ID:", 40f, y, boldPaint)
        canvas.drawText(receipt.studentId.ifEmpty { "NB-${receipt.userId.take(6).uppercase()}" }, 160f, y, regularPaint)
        y += 20f
        canvas.drawText("Account Email:", 40f, y, boldPaint)
        canvas.drawText(receipt.userEmail, 160f, y, regularPaint)

        // Transaction Details
        y += 35f
        canvas.drawText("TRANSACTION DETAILS", 40f, y, headerPaint)
        y += 20f
        canvas.drawText("Purpose:", 40f, y, boldPaint)
        canvas.drawText(receipt.purpose.replace("_", " "), 160f, y, regularPaint)
        y += 20f
        canvas.drawText("Description/Target:", 40f, y, boldPaint)
        canvas.drawText(receipt.targetName.ifEmpty { "Educational Services" }, 160f, y, regularPaint)
        y += 20f
        canvas.drawText("Reference/UTR:", 40f, y, boldPaint)
        canvas.drawText(receipt.transactionReference.ifEmpty { "NB-ONLINE-PAY" }, 160f, y, regularPaint)
        y += 20f
        canvas.drawText("Status:", 40f, y, boldPaint)
        canvas.drawText("VERIFIED & PAID", 160f, y, boldPaint.apply { color = Color.rgb(22, 163, 74) })

        // Total Amount Box
        y += 40f
        val boxPaint = Paint().apply { color = Color.rgb(238, 242, 255) }
        canvas.drawRect(40f, y, 555f, y + 55f, boxPaint)
        val amountTitlePaint = Paint().apply {
            color = Color.rgb(30, 41, 59)
            textSize = 14f
            isFakeBoldText = true
        }
        val amountPaint = Paint().apply {
            color = Color.rgb(15, 23, 42)
            textSize = 20f
            isFakeBoldText = true
        }
        canvas.drawText("Total Amount Paid:", 60f, y + 35f, amountTitlePaint)
        canvas.drawText("₹ ${receipt.amount}", 420f, y + 35f, amountPaint)

        // Footer / Stamp / Verification Notes
        y += 120f
        canvas.drawLine(40f, y, 555f, y, paint.apply { color = Color.LTGRAY; strokeWidth = 1f })
        y += 25f
        val notePaint = Paint().apply {
            color = Color.GRAY
            textSize = 10f
        }
        canvas.drawText("This is an electronically verified receipt generated by Neol Bharat Backend.", 40f, y, notePaint)
        y += 15f
        canvas.drawText("For inquiries or support, contact support@neolbharat.org.", 40f, y, notePaint)

        pdfDocument.finishPage(page)

        return try {
            val receiptsDir = File(context.cacheDir, "receipts")
            if (!receiptsDir.exists()) receiptsDir.mkdirs()
            val pdfFile = File(receiptsDir, "${receipt.receiptNumber}.pdf")
            val outputStream = FileOutputStream(pdfFile)
            pdfDocument.writeTo(outputStream)
            outputStream.flush()
            outputStream.close()
            pdfDocument.close()
            pdfFile
        } catch (e: Exception) {
            e.printStackTrace()
            pdfDocument.close()
            null
        }
    }
}
